/**
 * Vorlage-CSV mit nur der Kopfzeile (eine Zeile). BOM (\uFEFF) damit Excel UTF-8 korrekt erkennt.
 */
export function generateTemplateCSV() {
  const sep    = ';';
  const header = CSV_COLUMNS.map(c => c.label).join(sep);
  return '\uFEFF' + header;
}
